from datetime import datetime

from sqlalchemy import DateTime, Float, ForeignKey, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.models.base import Base


class Prediction(Base):
    """
    Stores prediction results generated by the ML model.
    """

    __tablename__ = "predictions"

    prediction_id: Mapped[int] = mapped_column(
        primary_key=True,
        autoincrement=True,
    )

    machine_id: Mapped[int] = mapped_column(
        ForeignKey("machines.machine_id"),
        nullable=False,
    )

    timestamp: Mapped[datetime] = mapped_column(
        DateTime,
        default=datetime.utcnow,
    )

    health_score: Mapped[float] = mapped_column(Float)

    failure_probability: Mapped[float] = mapped_column(Float)

    remaining_useful_life: Mapped[float] = mapped_column(Float)

    predicted_fault: Mapped[str] = mapped_column(
        String(100)
    )

    machine = relationship(
        "Machine",
        back_populates="predictions",
    )